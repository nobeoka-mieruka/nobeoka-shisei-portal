/**
 * 質問テーマの表記揺れ正規化辞書。
 * 会議録本文・質問要約に登場する語句が、意味は同じでも表記だけ異なる場合に統一する。
 * 意味の異なるテーマは統合しない（辞書に無い語句はそのまま使う）。
 *
 * 2026年8月時点では、実データ（前田遼・宮田博徳・甲斐忠篤の3議員分）にまだ表記揺れが
 * 発生していないため、この辞書は将来のために用意した骨組みであり、以下のエントリは
 * まだ実データに適用されていない（適用されたテーマにはnormalizedTopicFrom()で
 * 正規化前の原語を確認できる）。
 */
export const TOPIC_NORMALIZATION_MAP: Record<string, string> = {
  国スポ: "国民スポーツ大会・全国障害者スポーツ大会",
  障スポ: "国民スポーツ大会・全国障害者スポーツ大会",
  "国スポ・障スポ": "国民スポーツ大会・全国障害者スポーツ大会",
  国民スポーツ大会: "国民スポーツ大会・全国障害者スポーツ大会",
  全国障害者スポーツ大会: "国民スポーツ大会・全国障害者スポーツ大会",
  体育館エアコン: "学校体育館空調",
  "学校体育館の空調": "学校体育館空調",
  体育施設空調整備: "学校体育館空調",
  学校の空調: "学校体育館空調",
};

/** テーマ名を正規化する。辞書に無い場合は原語のまま返す。 */
export function normalizeTopicLabel(rawTopic: string): string {
  return TOPIC_NORMALIZATION_MAP[rawTopic] ?? rawTopic;
}
